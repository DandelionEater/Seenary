import assert from 'node:assert/strict';
import { createDetailCache } from '../src/utils/detailCache.ts';
let clock = 0, calls = 0, release;
const cache = createDetailCache(async key => {
  calls++;
  if (calls > 1) await new Promise(resolve => { release = resolve; });
  return `${key}:${calls}`;
}, { now: () => clock, ttl: 100 });
assert.deepEqual(await Promise.all([cache.get('anime:1'), cache.get('anime:1')]), ['anime:1:1', 'anime:1:1']);
assert.equal(calls, 1, 'concurrent page requests share one lookup');
assert.equal(await cache.get('anime:1'), 'anime:1:1');
assert.equal(calls, 1, 'repeat visits avoid network requests');
clock = 101;
assert.equal(await cache.get('anime:1'), 'anime:1:1', 'expired page returns while refresh is blocked');
await Promise.resolve();
assert.equal(calls, 2);
assert.equal(await cache.get('anime:1'), 'anime:1:1');
assert.equal(calls, 2, 'background refreshes coalesce');
release();
await new Promise(resolve => setImmediate(resolve));
assert.equal(await cache.get('anime:1'), 'anime:1:2', 'next visit sees refreshed details');
cache.clear();
const reload = cache.get('anime:1');
await Promise.resolve();
assert.equal(calls, 3, 'account changes clear the page cache');
release(); await reload;
const offline = createDetailCache(async () => { if (clock > 0) throw new Error('Offline'); return 'saved'; }, { now: () => clock, ttl: 100 });
clock = 0; await offline.get('page'); clock = 101;
assert.equal(await offline.get('page'), 'saved', 'refresh failure preserves the usable page');
console.log('PASS: immediate repeat/stale pages, request coalescing, refresh updates, and account invalidation.');
