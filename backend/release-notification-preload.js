const { ipcRenderer } = require('electron');
window.addEventListener('DOMContentLoaded', () => {
  ipcRenderer.on('release-notice:visible', () => { document.body.classList.add('visible'); });
  ipcRenderer.on('release-notice:fade-out', () => { document.body.classList.remove('visible'); });
  ipcRenderer.on('release-notice:data', (_event, value) => {
    document.getElementById('label').textContent = value.preview ? 'SEENARY · PREVIEW' : 'SEENARY · COMING SOON';
    document.getElementById('title').textContent = value.title;
    document.getElementById('message').textContent = value.message;
    const image = document.getElementById('cover');
    if (value.cover) { image.src = value.cover; image.hidden = false; }
    ipcRenderer.send('release-notice:resize', Math.ceil(document.querySelector('article').getBoundingClientRect().height) + 16);
  });
  document.getElementById('dismiss').addEventListener('click', () => ipcRenderer.send('release-notice:dismiss'));
  const card = document.querySelector('article');
  let drag = null;
  let suppressClick = false;
  card.addEventListener('pointerdown', event => {
    if (event.button !== 0 || event.target.closest('#dismiss')) return;
    card.classList.remove('snapping-back');
    drag = { id: event.pointerId, x: event.clientX, y: event.clientY, moved: false };
    suppressClick = false;
  });
  card.addEventListener('pointermove', event => {
    if (!drag || drag.id !== event.pointerId) return;
    const dx = event.clientX - drag.x;
    const dy = event.clientY - drag.y;
    if (!drag.moved && (Math.abs(dx) < 8 || Math.abs(dy) > Math.abs(dx))) return;
    drag.moved = true;
    card.setPointerCapture(event.pointerId);
    card.classList.add('dragging');
    card.style.transform = 'translateX(' + dx + 'px)';
    card.style.opacity = String(Math.max(0.25, 1 - Math.abs(dx) / 250));
  });
  function endDrag(event, cancelled) {
    if (!drag || drag.id !== event.pointerId) return;
    const threshold = Math.max(100, card.getBoundingClientRect().width * 0.3);
    const swipe = !cancelled && drag.moved && Math.abs(event.clientX - drag.x) >= threshold;
    suppressClick = drag.moved;
    drag = null;
    card.classList.remove('dragging');
    if (card.hasPointerCapture(event.pointerId)) card.releasePointerCapture(event.pointerId);
    if (swipe) ipcRenderer.send('release-notice:dismiss');
    else { if (suppressClick) card.classList.add('snapping-back'); card.style.transform = ''; card.style.opacity = ''; }
    // Suppress the click generated by pointerup, but allow the next deliberate click.
    setTimeout(() => { suppressClick = false; }, 0);
  }
  card.addEventListener('pointerup', event => endDrag(event, false));
  card.addEventListener('pointercancel', event => endDrag(event, true));
  card.addEventListener('lostpointercapture', event => endDrag(event, true));
  document.getElementById('open').addEventListener('click', event => {
    if (suppressClick) { event.preventDefault(); return; }
    ipcRenderer.send('release-notice:open');
  });
});
