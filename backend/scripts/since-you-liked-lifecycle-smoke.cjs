const assert = require('node:assert/strict');
const { fixture } = require('./since-you-liked-smoke');
const { Collection } = require('./atlas-metadata-smoke');
const { createSinceYouLikedService } = require('../atlas/sinceYouLiked');
const { exportAccountData, eraseAccountData } = require('../atlas/accountData');
async function main() {
  const base = fixture();
  base.repo.sinceYouLikedLifecycle = new base.repo.sinceYouLikedHidden.constructor();
  const libraryRepo = { libraryEntries:new Collection() };
  const mediaRepo = { media:new Collection() };
  let clock=Date.UTC(2026,9,19,10);
  const create=()=>createSinceYouLikedService({...base,libraryRepo,mediaRepo,now:()=>clock});
  let service=create();
  function seed(id,status='watching',type='ANIME') {
    const key=type+id;
    mediaRepo.media.rows.push({_id:key,type,anilistId:id});
    const entry={_id:'alice:'+key,userId:'alice',mediaId:key,type,status,deleted:false};
    libraryRepo.libraryEntries.rows.push(entry);
    return entry;
  }
  const pair=id=>({sourceMediaId:1,recommendedMediaId:id});
  const state=(id,track=false,type='ANIME')=>service.state('alice',{mediaType:type,pairs:[pair(id)],track});
  const watched=seed(10);
  assert.deepEqual((await state(10,true)).retainedMediaIds,[10]);
  watched.status='planned';assert.deepEqual((await state(10)).retainedMediaIds,[10]);
  watched.status='paused';assert.deepEqual((await state(10)).retainedMediaIds,[10]);
  watched.status='completed';await state(10);
  clock+=86400000-1;
  assert.equal(base.repo.sinceYouLikedFeedback.rows.length,0);
  await state(10);
  assert.equal(base.repo.sinceYouLikedFeedback.rows.length,0,'full 24 hours required');
  service=create();clock++;
  const completed=await state(10);
  assert.equal(completed.pairs[0].sinceYouLikedFeedback,'like');
  assert.deepEqual(completed.resolvedMediaIds,[10]);
  await state(10);assert.equal(base.repo.sinceYouLikedFeedback.rows.length,1,'auto-like once');
  const manual=seed(11,'completed');await state(11,true);
  clock+=23*3600000;
  await service.feedback('alice',{mediaType:'ANIME',...pair(11),feedback:'dislike'});
  clock+=2*3600000;
  assert.equal((await state(11)).pairs[0].sinceYouLikedFeedback,'dislike','manual reaction wins');
  const dropped=seed(12);await state(12,true);dropped.status='dropped';
  const droppedState=await state(12);
  assert.ok(droppedState.hiddenMediaIds.includes(12));
  assert.equal(droppedState.pairs[0].sinceYouLikedFeedback,null,'drop adds no dislike');
  const reset=seed(13,'completed');await state(13,true);clock+=23*3600000;
  reset.status='watching';await state(13);reset.status='completed';await state(13);clock+=2*3600000;
  assert.equal((await state(13)).pairs[0].sinceYouLikedFeedback,null,'re-completing starts a new full buffer');
  seed(14,'completed');await state(14,true);
  await service.hide('alice',{mediaType:'ANIME',mediaId:14,hidden:true});
  clock+=2*86400000;
  assert.equal((await state(14)).pairs[0].sinceYouLikedFeedback,null,'Not Interested never becomes an auto-like');
  seed(15,'completed');await state(15);
  assert.equal(base.repo.sinceYouLikedLifecycle.rows.some(row=>row.recommendedMediaId===15),false,'never auto-enroll unseen historical completions');
  seed(16,'completed','MANGA');await state(16,true,'MANGA');clock+=86400000;
  assert.equal((await state(16,false,'MANGA')).pairs[0].sinceYouLikedFeedback,'like','same lifecycle for manga');
  const away=seed(17);await state(17,true);clock+=3600000;
  away.status='completed';away.statusChangedAt=new Date(clock);clock+=25*3600000;
  assert.equal((await state(17)).pairs[0].sinceYouLikedFeedback,'like','completion timestamp survives time away from the recommendation page');
  await service.hide('alice',{mediaType:'ANIME',mediaId:12,hidden:false});
  assert.equal((await state(12)).hiddenMediaIds.includes(12),false,'restored dropped title is not immediately hidden again');
  dropped.status='watching';assert.ok((await state(12)).retainedMediaIds.includes(12),'changing dropped status makes restored suggestion eligible');
  dropped.status='dropped';assert.ok((await state(12)).hiddenMediaIds.includes(12),'a later drop is treated as Not Interested again');
  await service.feedback('alice',{mediaType:'ANIME',...pair(11),feedback:null});
  const restoredDislike=await state(11);
  assert.equal(restoredDislike.pairs[0].sinceYouLikedFeedback,null,'remove dislike clears shared reaction');
  assert.ok(restoredDislike.retainedMediaIds.includes(11),'remove dislike makes recommendation eligible again');
  const bob=await service.state('bob',{mediaType:'ANIME',pairs:[pair(10)]});
  assert.deepEqual(bob.retainedMediaIds,[],'account isolation');
  const exported=await exportAccountData(base.repo,{_id:'alice',username:'alice'});
  assert.ok(exported.data.sinceYouLikedLifecycle.length);
  await eraseAccountData(base.repo,'alice');
  assert.equal(base.repo.sinceYouLikedLifecycle.rows.length,0,'account deletion erases retention state');
  console.log('PASS: persisted 24-hour buffer, retention, explicit reactions, drop without dislike, re-completion reset, Not Interested, unseen history, manga, account export/deletion.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
